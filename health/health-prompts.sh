#!/usr/bin/env bash
# Сторож ТЕКСТОВ АГЕНТОВ: файл промпта в репозитории = ВЫКАЧЕННАЯ ревизия агента.
#
# **Зачем.** Связь «файл в репозитории ⇄ ревизия агента на платформе» держится форматом: `agents_md`
# предписывает «3–5 пунктов, до 12 строк», а парсер ждёт строки `NEWS|{json}` — при расхождении агент
# отвечает прозой, парсер её отбрасывает, и наружу уходит «ничего не нашёл» при ИСПРАВНОМ поиске. Ручная
# цель `make agent-prompts-check` эту связь не удерживает: правило без расписания разъезжается молча,
# поэтому у сверки есть таймер.
#
# **Почему БЕЗ алерта владельцу.** У соседей (`health-*.sh`) алерт — часть роли: служба может быть жива,
# а поведение уже сломано. Расхождение ПРОМПТА аварией бота не является — бот жив и отвечает; превращать
# это в сообщение в Telegram значило бы приучить владельца не читать алерты. Поэтому `POST /api/ops/alert`
# здесь НЕ вызывается и `BRIDGE_URL` не нужен. Результат видно журналом и кодом 1:
#   journalctl --user -u bridge-prompts.service
#   systemctl --user --failed
#
# **Почему НЕ лечит.** Лечить нечего: это сверка двух копий ТЕКСТА. Автоправка промпта — это ВЫКАТ, то
# есть решение владельца (`make agent-prompts-deploy AGENT=<агент>`), а не автоматика сторожа.
set -uo pipefail   # НЕ `-e`: код сверки и есть результат, его нельзя проглотить

#: Корни: `$INFRA` — обвязка, `$WORKSPACE` — воркспейс (там `.env` и окружения продуктов).
#: Путь к воркспейсу — НАСТРОЙКА (`AGENT_WORKSPACE`, её задаёт юнит), а не расположение файла: переезд
#: `infra/` в свой репозиторий иначе сломал бы сторожа молча.
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/../lib/workspace.sh"

# Режим платформы: сверка идёт с ЖИВОЙ ревизией агента через HTTP API платформы, а у вендора без такой
# возможности (`http_api=no` в `infra/vendors.tsv`)
# платформа погашена осознанно ⇒ сверять не с чем. Пропуск НАЗВАН и завершается НУЛЁМ: у этого сторожа нет
# ни алерта, ни лечения, поэтому код 1 здесь означал бы вечно `failed` таймер, а не поломку.
vendor="$(sed -n 's/^PLATFORM_VENDOR=//p' "$WORKSPACE/.env" 2>/dev/null | head -1 | tr -d '"'"'"'' | tr -d '[:space:]')"
if [[ -n "$vendor" ]] && [[ "$(vendor_capability "$vendor" http_api)" != "yes" ]]; then
  echo "[health-prompts] не проверяется: PLATFORM_VENDOR=$vendor — ревизии платформы недоступны осознанно"
  echo "[health-prompts] ok (пропуск назван)"
  exit 0
fi

# Механизм сверки ОДИН — тот же скрипт, что у `make agent-prompts-check`: две «формы расхождения»
# разошлись бы молча. Промпты лежат у корня воркспейса, поэтому идём туда; скрипт берём из обвязки
# (`$INFRA`), а не от текущего каталога.
cd "$WORKSPACE" || { echo "[health-prompts] ОСТАНОВ: не зайти в $WORKSPACE" >&2; exit 2; }
python3 "$INFRA/vendor-bringup/agent-prompts.py" check
rc=$?

if [[ "$rc" -eq 0 ]]; then
  echo "[health-prompts] ok"
else
  echo "[health-prompts] FAIL (код $rc): текст промпта разошёлся с выкаченной ревизией —" >&2
  echo "  выкат: python3 "$INFRA/vendor-bringup/agent-prompts.py" deploy <агент>   (агенты — в agent-prompts.tsv)" >&2
  echo "  ❗ код 1 у сверки означает И «расхождение», И «не смог проверить» (нет сети/файла)." >&2
  echo "     Что именно — видно по тексту выше: «РАСХОЖДЕНИЙ» против «ОТКАЗ сети»." >&2
fi
exit "$rc"
