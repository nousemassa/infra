#!/usr/bin/env bash
# Сторож ДРЕЙФА конфигурации: контейнер отстал от объявленного окружения → алерт.
#
# **Зачем.** `env_file: .env` читается при СОЗДАНИИ контейнера, поэтому после правки `.env` работающий
# контейнер живёт со старым значением: неразрешимый адрес эмбеддингов даёт полнотекстовый поиск вместо
# гибридного (замер: 0 находок против 3), а служба при этом `healthy` — отказ виден только тому, кто
# специально пошёл его искать.
#
# **Почему алерт ОДИН на состояние, а не каждые 5 минут.** Повтор одного и того же сообщения учит
# владельца смотреть не ту службу. Дрейф сам не исчезнет, поэтому повторять его каждые пять минут
# бессмысленно и вредно: шлём при ПОЯВЛЕНИИ (подпись изменилась) и отдельно при СНЯТИИ — чтобы было
# видно, что вопрос закрыт.
#
# **Почему сторожа нет у гейта `make drift`.** Это разные роли: гейт вызывают руками перед выкатом,
# сторож — расписание. Механизм сверки один (тот же скрипт), иначе две «формы, что считать дрейфом».
#
# **Почему НЕТ автолечения.** Пересоздание контейнера прерывает сессию Telegram — это решение
# владельца и тихое время, а не автоматика. Сторож называет службу, ключ и команду.
set -uo pipefail

#: Корни: `$INFRA` — сама обвязка, `$WORKSPACE` — воркспейс (там `.env` и каталоги проектов).
#: Взяты из ОДНОГО места: путь к воркспейсу — настройка (`AGENT_WORKSPACE`, её задают юниты),
#: а не расположение файла — иначе переезд `infra/` в свой репозиторий сломает скрипт молча.
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/../lib/workspace.sh"
# ЕДИНЫЙ вход доставки алерта: мост → MTProto без моста → маркер.
source "$INFRA/lib/alert.sh"
CHECK="$INFRA/checks/check-stack-drift.py"
# Доставка — ОБЩИЙ вход (`infra/lib/alert.sh`): мост → MTProto без моста → маркер+журнал.
# Подпись последнего состояния дрейфа: по ней видно и появление, и снятие.
STATE_FILE="${TMPDIR:-/tmp}/agent-health-drift-state"

report="$(python3 "$CHECK" 2>&1)"; rc=$?
# Подпись — сами расхождения без длинных «что делать»: так изменение дрейфа видно как изменение подписи.
signature="$(printf '%s\n' "$report" | sed -n 's/^  \([^:]*: [^:]*\):.*/\1/p' | sort | tr '\n' '|')"
previous="$(cat "$STATE_FILE" 2>/dev/null | tr -d '\n')"

if [[ "$rc" -ne 0 ]]; then
  echo "[health-drift] FAIL: контейнер отстал от объявленного окружения"
  printf '%s\n' "$report" | sed 's/^/  /'
  if [[ "$signature" != "$previous" ]]; then
    alert_send "[health-drift]" "дрейф конфигурации (контейнер отстал от .env, служба при этом жива): $(printf '%s' "$signature" | tr '|' ';') — пересоздать в тихое время командой из вывода; подробности: make drift"
  fi
  printf '%s' "$signature" > "$STATE_FILE"
  exit 1
fi

if [[ -n "$previous" ]]; then
  alert_send "[health-drift]" "дрейф конфигурации снят: контейнеры снова совпадают с объявленным окружением"
fi
printf '' > "$STATE_FILE"
echo "[health-drift] ok"
exit 0
