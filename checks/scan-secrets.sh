#!/usr/bin/env bash
# scan-secrets.sh — искать секреты в том, что готовится к публикации или коммиту.
#
# Один источник для двух потребителей:
#   * сборщик публичного снапшота — перед сборкой публичного дерева;
#   * джоба `secrets` в CI — на каждый push и pull request.
# Второй копии паттернов быть не должно: разойдутся — и гейт перестанет быть гейтом.
#
# Что ищем:
#   1. идентификатор Telegram-канала: `-100` + не менее 9 цифр;
#   2. ключи провайдеров: `sk-…`;
#   3. токены ботов: `<8-10 цифр>:<30+ символов>`;
#   4. файлы, которых не должно быть в индексе: `.env`, `*.session`;
#   5. ключи NVIDIA `nvapi-…` и секретные ФАЙЛЫ ПО ПУТИ: `api_keys.txt` (ключи триады llama.cpp),
#      `.ngc/`, `.nvapi`. Файлы живут ВНЕ репозитория (каталог сборки моделей, `$HOME`),
#      поэтому проверяется ПУТЬ, а не содержимое: содержимое сканеру недоступно и не нужно.
#      Это не формальность: юнит и образ ссылаются на `api_keys.txt` ХОСТОВЫМ путём, и именно так
#      файл однажды может уехать в снапшот вместе с ним.
#
# Использование:
#   bash infra/checks/scan-secrets.sh            # проверить файлы под git (с учётом .gitignore)
#   bash infra/checks/scan-secrets.sh <каталог>  # проверить готовое дерево (например, снапшот)
set -euo pipefail

#: Корни: `$INFRA` — сама обвязка, `$WORKSPACE` — воркспейс (там `.env` и каталоги проектов).
#: Взяты из ОДНОГО места: путь к воркспейсу — настройка (`AGENT_WORKSPACE`, её задают юниты),
#: а не расположение файла — иначе переезд `infra/` в свой репозиторий сломает скрипт молча.
CHECKS_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/../lib/workspace.sh"
TARGET="${1:-}"

# Плейсхолдер из примеров Telegram: он же используется в наших тестах и в подсказке
# инструментом разового разрешения канала. Это НЕ боевой идентификатор — исключаем, иначе
# сканер ловит сам себя и перестаёт быть гейтом.
PLACEHOLDER='1001234567890'

fail=0

report() {
  fail=1
  echo "[secrets] FAIL: $1" >&2
}

# --- список файлов ---------------------------------------------------------------
if [[ -n "$TARGET" ]]; then
  [[ -d "$TARGET" ]] || { echo "[secrets] нет каталога: $TARGET" >&2; exit 2; }
  files() { find "$TARGET" -type f; }
  label="$TARGET"
else
  # Файлы НАШИХ репозиториев с учётом .gitignore каждого (`.env`, `*.session`, `vendor/`, `hh/`
  # отсеиваются сами). ❗ Список берётся у общего помощника, а НЕ у `git ls-files` по корню: папки
  # проектов отслеживают их собственные репозитории, и прямой вызов ослеп бы молча — сканер перестал
  # бы видеть `.env` в проектах, оставаясь зелёным.
  files() { bash "$CHECKS_DIR/list-our-files.sh" | sed "s|^|$WORKSPACE/|"; }
  label="наши репозитории (корень + проекты из repos.tsv)"
fi

echo "[secrets] проверяю: $label"

# --- 1. идентификаторы каналов ---------------------------------------------------
channel_hits="$(files | xargs -r grep -InE -- '-100[0-9]{9,}' 2>/dev/null | grep -v -- "$PLACEHOLDER" || true)"
if [[ -n "$channel_hits" ]]; then
  report "похоже на идентификатор Telegram-канала"
  echo "$channel_hits" | head -5 >&2
fi

# --- 2-3. ключи и токены ---------------------------------------------------------
# `nvapi-…` — формат ключа NVIDIA NGC (им пользуется контейнерный рантайм: `docker login nvcr.io`).
key_pattern='sk-[A-Za-z0-9]{20,}|nvapi-[A-Za-z0-9_-]{20,}|[0-9]{8,10}:[A-Za-z0-9_-]{30,}'
token_hits="$(files | xargs -r grep -InE -- "$key_pattern" 2>/dev/null | grep -v -- "$PLACEHOLDER" || true)"
if [[ -n "$token_hits" ]]; then
  report "похоже на ключ провайдера или токен бота"
  echo "$token_hits" | head -5 >&2
fi

# --- 4. файлы, которых не должно быть в индексе ----------------------------------
if [[ -z "$TARGET" ]]; then
  # ❗ Индекс КАЖДОГО репозитория, а не только корня: файлы проектов отслеживают ИХ репозитории, и
  # проверка одного корня стала бы тривиально зелёной — секрет мог бы уехать молча.
  for repo in $(bash "$CHECKS_DIR/list-our-files.sh" --repos); do
    tracked_bad=$(git -C "$repo" ls-files | grep -E '(^|/)\.env$|\.session$|\.session-journal$' || true)
    if [[ -n "$tracked_bad" ]]; then
      report "в индексе git секретные файлы ($(basename "$repo"))"
      echo "$tracked_bad" | head -5 >&2
    fi
  done
fi

# --- 5. секретные файлы по ПУТИ (содержимое вне репозитория) ----------------------
# Один и тот же список имён для индекса и для публикуемого дерева: разойдутся — гейт перестанет
# ловить вторую половину. `api_keys.txt` ищется и как имя, и как каталог с ним.
secret_paths='(^|/)api_keys\.txt$|(^|/)\.ngc(/|$)|(^|/)\.nvapi(/|$)'
path_hits="$(files | grep -E "$secret_paths" || true)"
if [[ -n "$path_hits" ]]; then
  report "секретный файл попал в проверяемый набор (содержимое таких файлов хранится вне репозитория)"
  echo "$path_hits" | head -5 >&2
fi

if [[ "$fail" -ne 0 ]]; then
  echo "[secrets] проверка не пройдена — уберите находки из публикуемого набора" >&2
  exit 1
fi

echo "[secrets] чисто: боевых идентификаторов, ключей и токенов не найдено"
echo "[secrets] (плейсхолдер $PLACEHOLDER в тестах и подсказках — намеренно игнорируется)"
