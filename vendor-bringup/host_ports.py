"""Хостовые адреса НАШИХ баз — один источник для питоновских скриптов.

**Зачем отдельным модулем.** `.env` хранит адреса ВНУТРИ docker-сети (`realty-db:5432`, `news-db:5432`), а
хостовый процесс таких имён не разрешает: ему нужен опубликованный порт на `127.0.0.1`. Эта подмена жила
копией в четырёх скриптах — и копии разъехались: литерал старого хостового порта указывал бы на ЧУЖОЙ
postgres, и скрипт писал бы в него.

**Почему неизвестный хост — ОТКАЗ.** Тихий откат «нет в карте ⇒ 5432» даёт ту же картину, что и мёртвая
база, и причину потом ищут не там. Пусть падает с названным именем хоста.

Для shell-скриптов тот же смысл даёт `infra/lib/dsn.sh` (`dsn`, `vector_dsn`, `graph_dsn`).
"""

import re

#: Опубликованные на 127.0.0.1 порты наших контейнеров. Ключ — ИМЯ СЛУЖБЫ из DSN. Вендорского
#: `postgres` здесь нет намеренно: его сервер — чужой, и молчаливое «знаю порт» увело бы туда наши данные.
PORTS = {"realty-db": 55435, "news-db": 55436, "pgvector": 55433,
         "graph-db": 55434, "reminders-db": 55434}

_AT = re.compile(r"@([^:@/]+)(?::\d+)?/")


def published_port(hostname: str) -> int:
    port = PORTS.get(hostname)
    if port is None:
        raise SystemExit(
            f"[host_ports] хост базы {hostname!r} неизвестен: опубликованные порты знаю для "
            f"{sorted(PORTS)} — добавьте службу в карту, а не полагайтесь на 5432"
        )
    return port


def host_dsn(dsn: str) -> str:
    """DSN из `.env` → DSN для хоста: имя службы заменяется на `127.0.0.1:<опубликованный порт>`.

    Креды и имя базы НЕ трогаются: они и есть источник правды, менять их здесь значило бы развести
    пароли контейнера и хоста.
    """
    raw = dsn.strip()
    match = _AT.search(raw)
    if not match:
        raise SystemExit(f"[host_ports] в DSN нет адреса вида user@host/db: {raw!r}")
    port = published_port(match.group(1))
    return _AT.sub(f"@127.0.0.1:{port}/", raw, count=1)
