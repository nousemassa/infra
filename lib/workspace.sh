#!/usr/bin/env bash
# Где воркспейс — ОДНО место для всей рабочей обвязки (`infra/`).
#
# **Зачем настройка, а не только путь от файла.** У обвязки два корня: свой (`INFRA` — откуда взяты её
# же скрипты, сторожа и помощники) и корень ВОРКСПЕЙСА (`WORKSPACE` — там `.env` и каталоги проектов).
# Пока `infra/` лежит внутри воркспейса, корень воркспейса выводится из первого (`infra/..`), но
# `infra/` можно вынести в ОТДЕЛЬНЫЙ репозиторий — и тогда путь от файла перестанет указывать на воркспейс.
#
# Правило проекта: **путь к данным — настройкой, а не от расположения кода.** Если путь вычисляется от
# `__file__`, переезд модуля уводит его внутрь `site-packages`, и бот МОЛЧА не подключается при зелёных
# тестах и зелёном гейте. Поэтому порядок такой:
# сначала `AGENT_WORKSPACE` (её задают юниты через `Environment=`, то есть развёртывание), затем —
# вывод от файла (для ручных запусков из воркспейса).
#
# Подключение (путь считается от САМОГО вызывающего файла):
#   source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/../lib/workspace.sh"   # из infra/<папка>/<скрипт>
#   source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/../lib/workspace.sh"      # из infra/<скрипт>
# После подключения доступны: `$INFRA` (рабочая обвязка), `$WORKSPACE` (воркспейс).

INFRA="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WORKSPACE="${AGENT_WORKSPACE:-$(cd "$INFRA/.." && pwd)}"

#: Проверка «воркспейс — это правда воркспейс»: без неё ошибка в `AGENT_WORKSPACE` дала бы сторожу
#: пустой `.env` и службу «не найдено» вместо внятного отказа (класс «зелёный при мёртвом»).
if [[ ! -f "$WORKSPACE/.env" ]]; then
  echo "[infra] ОСТАНОВ: воркспейс не найден — нет $WORKSPACE/.env." >&2
  echo "        Задайте AGENT_WORKSPACE (юниты задают её через Environment=) или запускайте из воркспейса." >&2
  return 1 2>/dev/null || exit 1
fi
